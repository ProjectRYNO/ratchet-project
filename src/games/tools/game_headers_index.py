#!/usr/bin/env python3
"""game_headers_index.py [--check] : index the shared game types and find duplicate struct definitions.

Writes dl/DOCS/types/GAME_HEADERS.md (which header owns each struct/typedef in dl/code/game/*.h and
dl/code/include/vector-like headers). With --check, prints `DUPLICATE TYPE:` lines for every struct a
code/game .cpp file defines that a header already defines, or that two or more .cpp files define.
Run from anywhere; paths are relative to this file.
"""
import collections
import glob
import os
import re
import sys

DL = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'dl')
STRUCT = re.compile(r'^(?:typedef\s+)?struct\s+([A-Za-z_]\w*)\s*\{', re.M)
ANON = re.compile(r'^typedef\s+struct\s*\{.*?^\}\s*([A-Za-z_]\w*)\s*;', re.M | re.S)
TYPEDEF = re.compile(r'^typedef\s+[^;{}]*?\b([A-Za-z_]\w*)\s*(?:\[[^\]]*\])?\s*;', re.M)


def header_types():
	owners = collections.OrderedDict()
	for path in sorted(glob.glob(os.path.join(DL, 'code', 'game', '*.h'))):
		text = open(path, errors='replace').read()
		names = STRUCT.findall(text) + ANON.findall(text) + TYPEDEF.findall(text)
		seen = []
		for n in names:
			if n not in seen:
				seen.append(n)
		owners[os.path.basename(path)] = seen
	return owners


def write_index(owners):
	lines = ['# Shared game types', '',
		'Generated by `src/games/tools/game_headers_index.py`; do not edit by hand.', '',
		'Each shared struct or typedef lives in exactly one header in `code/game/`, named after the module that',
		'owns it (as in the prototype\'s `game_dl/*.h`). Include that header instead of defining a local copy.',
		'Vector and matrix types (`vec2`, `vec3`, `vec4`, `vec4f`, `quat`, `mtx3`, `mtx4`, `BSphere`, `qword`)',
		'are in `vector.h`. Layouts come from `dltypes.txt`. `game_round.sh` prints `DUPLICATE TYPE:` when a',
		'`.cpp` redefines one of these or two `.cpp` files define the same struct.', '',
		'| Header | Types |', '|---|---|']
	for h, names in owners.items():
		if names:
			lines.append('| `%s` | %s |' % (h, ', '.join('`%s`' % n for n in names)))
	out = os.path.join(DL, 'DOCS', 'types', 'GAME_HEADERS.md')
	with open(out, 'w', newline='\n') as f:
		f.write('\n'.join(lines) + '\n')
	return out


def check(owners):
	in_header = {n: h for h, names in owners.items() for n in names}
	defined = collections.defaultdict(list)
	for path in sorted(glob.glob(os.path.join(DL, 'code', 'game', '*.cpp'))):
		for n in STRUCT.findall(open(path, errors='replace').read()):
			defined[n].append(os.path.basename(path))
	bad = 0
	for n, files in sorted(defined.items()):
		if n in in_header:
			print('DUPLICATE TYPE: %s is in %s but also defined in %s' % (n, in_header[n], ', '.join(files)))
			bad += 1
		elif len(files) > 1:
			print('DUPLICATE TYPE: %s defined in %s' % (n, ', '.join(files)))
			bad += 1
	return bad


if __name__ == '__main__':
	owners = header_types()
	if '--check' in sys.argv:
		check(owners)
	else:
		print(write_index(owners))
		check(owners)
